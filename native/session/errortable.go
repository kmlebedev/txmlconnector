// InternalErrorText returns the RU text of one internal DLL error code.
func InternalErrorText(code int) (string, bool) {
	text, ok := internalErrorTexts[code]
	return text, ok
}

// FormatInternalError renders the DLL "{%d} %s" form used for library errors
// (docs/protocol/errors.md, D); unknown codes are not formatted.
func FormatInternalError(code int) (string, bool) {
	text, ok := internalErrorTexts[code]
	if !ok {
		return "", false
	}
	return fmt.Sprintf("{%d} %s", code, text), true
}

// TransactionErrorText returns the RU text of the RQ_TRANSACT server codes 1..6
// (O). Codes 7..66 are not recovered (I) and render as Unknown error.
func TransactionErrorText(code byte) (string, bool) {
	switch code {
	case 1:
		return "Клиент не допущен к торгам.", true
	case 2:
		return "Трейдер не допущен к торгам.", true
	case 3:
		return "Клиент не обслуживается данным Трейдером.", true
	case 4:
		return "Сделки с собой запрещены.", true
	case 5:
		return "Попытка снять несуществующую заявку.", true
	case 6:
		return "Транзакции не разрешены.", true
	default:
		return "", false
	}
}
